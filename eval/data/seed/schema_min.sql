CREATE OR REPLACE FUNCTION public.update_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  new.updated_at = now();
  RETURN new;
END;
$$;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.articles
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.topics
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.events
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.article_ai_results
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at();


-- event_articles 에 행이 들어올 때마다 events 의 집계 컬럼을 올린다.
-- 파이프라인이 이 트리거에 의존해 article_count 를 유지하므로 스키마에 포함하지만,
-- 시드를 넣을 때는 반드시 꺼야 한다 (아래 "시드 적용 절차" 참고).
CREATE OR REPLACE FUNCTION public.update_event_counts_on_article_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_bias_type public.bias_type;
BEGIN
  SELECT bias_type INTO v_bias_type
  FROM public.articles
  WHERE id = NEW.article_id;

  UPDATE public.events
  SET
    article_count = article_count + 1,
    left_count    = left_count    + CASE WHEN v_bias_type = '진보' THEN 1 ELSE 0 END,
    mid_count     = mid_count     + CASE WHEN v_bias_type = '중도' THEN 1 ELSE 0 END,
    right_count   = right_count   + CASE WHEN v_bias_type = '보수' THEN 1 ELSE 0 END
  WHERE id = NEW.event_id;

  RETURN NEW;
END;
$$;

CREATE TRIGGER update_event_counts_on_article_insert
AFTER INSERT ON public.event_articles
FOR EACH ROW EXECUTE FUNCTION public.update_event_counts_on_article_insert();


-- =============================================================
-- 시드 적용 절차
--
-- events_2026-07-27.sql 은 events 에 article_count / left / mid / right 값을
-- 이미 채워서 넣는다. 그 상태로 event_articles 722행을 INSERT 하면 위 트리거가
-- 행마다 +1 을 해서 집계가 정확히 2배가 된다.
--
-- 토픽 분류 대상 선정이 (article_count - abusing_count) 기준이라, 2배가 되면
-- 기사 3건짜리 이벤트가 6건으로 보여 대상 집합이 통째로 달라진다.
--
-- 그래서 이렇게 넣는다:
--
--   -- 1) 기사
--   \i articles_2026-07-20.sql
--
--   -- 2) 트리거 끄기
--   ALTER TABLE public.event_articles DISABLE TRIGGER update_event_counts_on_article_insert;
--
--   -- 3) 이벤트
--   \i events_2026-07-27.sql
--
--   -- 4) 트리거 다시 켜기
--   ALTER TABLE public.event_articles ENABLE TRIGGER update_event_counts_on_article_insert;
