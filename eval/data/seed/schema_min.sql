-- =============================================================
-- 시드 데이터용 최소 스키마 (토픽 분류 담당자용)
--
-- articles_2026-07-20.sql 과 events_2026-07-27.sql 이 들어갈 테이블만 만든다.
-- hannoon-supabase 의 마이그레이션 38개 중 파이프라인이 실제로 쓰는 부분만
-- 추려낸 것이라, 앱 기능(프로필/구독/알림/RLS/RPC 함수)은 들어 있지 않다.
--
-- hannoon-supabase 저장소에 접근할 수 있다면 이 파일 대신
-- `supabase db reset` 을 쓰는 편이 낫다 — 그쪽이 원본이다.
--
-- 적용 순서
--   1) 이 파일
--   2) articles_2026-07-20.sql   (기사 2,578건)
--   3) events_2026-07-27.sql     (이벤트 222 / event_articles 722 / article_ai_results 722)
--
--   ⚠️ 2)와 3) 사이가 아니라, 3) 을 넣기 전에 파일 맨 아래 "시드 적용 절차"의
--      트리거 비활성화를 반드시 읽을 것. 그냥 넣으면 article_count 가 2배가 된다.
--
-- 전제: PostgreSQL 15+ / pgvector 사용 가능
-- =============================================================


-- =============================================================
-- 1. 확장
-- =============================================================

-- Supabase 는 확장을 extensions 스키마에 둔다. 순수 Postgres 에는 그 스키마가
-- 없으므로 만들어 준다(이미 있으면 넘어간다).
CREATE SCHEMA IF NOT EXISTS extensions;

-- 임베딩 저장/검색용. 4096차원을 쓴다.
CREATE EXTENSION IF NOT EXISTS vector SCHEMA extensions;


-- =============================================================
-- 2. Enum 타입
-- =============================================================

CREATE TYPE public.category      AS ENUM ('정치', '경제', '사회', '국제');
CREATE TYPE public.bias_type     AS ENUM ('진보', '중도', '보수');
CREATE TYPE public.content_source AS ENUM ('rss', 'crawl');
CREATE TYPE public.article_status AS ENUM ('needs_crawl', 'ready', 'crawl_failed');

-- 'event_assigned' 는 이벤트 분류가 끝난 기사를 뜻한다.
-- 시드의 article_ai_results 722행이 전부 이 값이다.
CREATE TYPE public.article_ai_status AS ENUM ('pending', 'done', 'failed', 'event_assigned');


-- =============================================================
-- 3. 테이블
-- =============================================================

-- -------------------------------------------------------------
-- articles — 원천 기사
-- -------------------------------------------------------------
CREATE TABLE public.articles (
  id                bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  feed_url          text                    NOT NULL,
  guid              text,
  link              text                    NOT NULL,
  category          public.category         NOT NULL,
  title             text                    NOT NULL,
  summary           text                    NOT NULL,
  content           text,
  content_source    public.content_source   NOT NULL,
  publisher         text                    NOT NULL,
  published_at      timestamp               NOT NULL,
  bias_type         public.bias_type        NOT NULL,
  status            public.article_status   NOT NULL,
  article_image_url text,
  created_at        timestamp               NOT NULL DEFAULT now(),
  updated_at        timestamp               NOT NULL DEFAULT now(),
  core_content      text,
  embedding         extensions.vector(4096),
  CONSTRAINT articles_pkey PRIMARY KEY (id)
);

-- -------------------------------------------------------------
-- topics — 토픽 (분류 결과가 여기 쌓인다)
--
-- parent_topic_id IS NULL → 최상위 토픽
-- parent_topic_id = <id>  → 그 부모 아래 서브토픽(leaf). events.topic_id 는 leaf만 참조.
-- 서브토픽을 안 쓰면 전부 NULL 로 남아 평면 구조로 동작한다.
-- -------------------------------------------------------------
CREATE TABLE public.topics (
  id              bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  category        public.category NOT NULL,
  title           text            NOT NULL,
  summary         text            NOT NULL,
  created_at      timestamp       NOT NULL DEFAULT now(),
  updated_at      timestamp       NOT NULL DEFAULT now(),
  parent_topic_id bigint,
  CONSTRAINT topics_pkey PRIMARY KEY (id),
  CONSTRAINT topics_parent_topic_id_fkey FOREIGN KEY (parent_topic_id)
    REFERENCES public.topics(id) ON DELETE SET NULL
);

-- -------------------------------------------------------------
-- events — 이벤트 (토픽 분류의 입력)
--
-- topic_id 는 NULL 허용이다. 토픽 분류 전 상태를 표현해야 하기 때문이고,
-- 시드의 222행은 전부 NULL 로 들어온다.
-- -------------------------------------------------------------
CREATE TABLE public.events (
  id              bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  topic_id        bigint,
  category        public.category NOT NULL,
  title           text            NOT NULL,
  summary         text            NOT NULL,
  article_count   integer         NOT NULL DEFAULT 0 CHECK (article_count >= 0),
  left_count      integer         NOT NULL DEFAULT 0 CHECK (left_count    >= 0),
  mid_count       integer         NOT NULL DEFAULT 0 CHECK (mid_count     >= 0),
  right_count     integer         NOT NULL DEFAULT 0 CHECK (right_count   >= 0),
  abusing_count   integer         NOT NULL DEFAULT 0 CHECK (abusing_count >= 0),
  event_image_url text,
  created_at      timestamp       NOT NULL DEFAULT now(),
  updated_at      timestamp       NOT NULL DEFAULT now(),
  prev_event_id   bigint,
  next_event_id   bigint,
  reason          text,
  core_content    text,
  embedding_text  text,
  embedding       extensions.vector(4096),
  CONSTRAINT events_pkey PRIMARY KEY (id),
  CONSTRAINT events_topic_id_fkey   FOREIGN KEY (topic_id)      REFERENCES public.topics(id),
  CONSTRAINT events_prev_event_fkey FOREIGN KEY (prev_event_id) REFERENCES public.events(id),
  CONSTRAINT events_next_event_fkey FOREIGN KEY (next_event_id) REFERENCES public.events(id)
);

-- -------------------------------------------------------------
-- event_articles — 이벤트 ↔ 기사 연결
-- reason 에 LLM 의 배정 근거가 들어 있다.
-- -------------------------------------------------------------
CREATE TABLE public.event_articles (
  id         bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  event_id   bigint NOT NULL,
  article_id bigint NOT NULL,
  reason     text,
  CONSTRAINT event_articles_pkey PRIMARY KEY (id),
  CONSTRAINT event_articles_event_id_fkey   FOREIGN KEY (event_id)   REFERENCES public.events(id),
  CONSTRAINT event_articles_article_id_fkey FOREIGN KEY (article_id) REFERENCES public.articles(id)
);

-- -------------------------------------------------------------
-- article_ai_results — 기사별 LLM 산출물 + 파이프라인 상태
-- 토픽 분류기는 여기를 직접 읽지 않지만, 이벤트가 어느 단계까지 왔는지를
-- status 로 판단하는 코드가 있어 시드에 포함돼 있다.
-- -------------------------------------------------------------
CREATE TABLE public.article_ai_results (
  id          bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  article_id  bigint                  NOT NULL,
  summary     text,
  abuse_score numeric,
  abuse_label text,
  keywords    text[],
  status      public.article_ai_status NOT NULL DEFAULT 'pending',
  last_error  text,
  created_at  timestamp                NOT NULL DEFAULT now(),
  updated_at  timestamp                NOT NULL DEFAULT now(),
  CONSTRAINT article_ai_results_pkey PRIMARY KEY (id),
  CONSTRAINT article_ai_results_article_id_key UNIQUE (article_id),
  CONSTRAINT article_ai_results_article_id_fkey FOREIGN KEY (article_id)
    REFERENCES public.articles(id) ON DELETE CASCADE
);

-- -------------------------------------------------------------
-- topic_causes — 토픽별 원인 문장과 임베딩
-- 토픽 후보 검색이 이 테이블의 cause_embedding 을 훑는다. 시드에는 없고,
-- 토픽 분류를 돌리면 여기 쌓인다.
-- -------------------------------------------------------------
CREATE TABLE public.topic_causes (
  id              bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  topic_id        bigint NOT NULL,
  cause_text      text   NOT NULL,
  cause_embedding extensions.vector(4096),
  CONSTRAINT topic_causes_pkey PRIMARY KEY (id),
  CONSTRAINT topic_causes_topic_id_fkey FOREIGN KEY (topic_id) REFERENCES public.topics(id)
);


