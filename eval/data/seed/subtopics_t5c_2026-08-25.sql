  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id     bigint NOT NULL REFERENCES public.topics(id) ON DELETE CASCADE,
  name         text   NOT NULL,
  perspective  text,
  reason       text,
  created_at   timestamp NOT NULL DEFAULT now(),
  updated_at   timestamp NOT NULL DEFAULT now(),
  UNIQUE (topic_id, name)
);
CREATE INDEX IF NOT EXISTS subtopics_topic_id_idx ON public.subtopics (topic_id);

CREATE TABLE IF NOT EXISTS public.subtopic_events (
  subtopic_id  bigint NOT NULL REFERENCES public.subtopics(id) ON DELETE CASCADE,
  event_id     bigint NOT NULL REFERENCES public.events(id)    ON DELETE CASCADE,
  created_at   timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (subtopic_id, event_id)
);
CREATE INDEX IF NOT EXISTS subtopic_events_event_id_idx ON public.subtopic_events (event_id);

