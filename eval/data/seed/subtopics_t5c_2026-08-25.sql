--   하나에 배정하는 분류가 아니라, 같은 이벤트를 여러 관점에서 다시 보여주는 구조다.
--   토픽 5개 / 이벤트 54건 / 서브토픽 20개 / 귀속 68쌍(이벤트당 1.26)
--   어느 서브토픽에도 안 들어간 '단독 이벤트' 14건(25.9%) — subtopic_events 에 한 줄도 없는 이벤트가 곧 단독이다.
--   전수 감사 적합률 69.1% (47/68쌍).
--
-- 어떻게 만들었나 (프롬프트)
--   2단계다. 자세한 규칙과 근거는 docs/subtopic_prompt_guide.md 를 볼 것.
--     1단계  이벤트마다 라벨 2~4개를 뽑아 임베딩으로 묶고, 2건 이상 모인 묶음만
--            관점으로 승격한 뒤 이름을 붙인다(bottom-up). 관점의 근거가 모델의
--            자기 신고가 아니라 라벨의 실제 분포에서 나온다.
--     2단계  (이벤트, 서브토픽) 쌍마다 예/아니오만 묻고 원문 인용을 요구한다.
--            인용이 이벤트 원문에 없으면 코드가 그 귀속을 폐기한다.
--   한 번에 '관점 발견 + 귀속'을 시키면 둘이 서로를 갉아먹어서 단계를 나눴다.
--   판정 단위를 쪼갤수록 좋아진다는 것이 이 실험 전체의 교훈이다(적합률 46.1% → 74.1%).
--
-- 전제
--   eval/data/seed/schema_min.sql → articles_2026-07-20.sql → events_2026-07-27.sql
--   순서로 먼저 적용해야 한다. 여기 귀속이 참조하는 이벤트가 그 안에 있다.
--   기사·이벤트 시드와 apply_local_seed.py 는 이 브랜치에 없다 — 프로덕션 코드 변경과
